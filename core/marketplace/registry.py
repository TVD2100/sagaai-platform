"""
core.marketplace.registry - installed-entity registry backed by SQLite.

The marketplace keeps its own record of what it installed in the
``marketplace_installed`` table of ``sagaai.db`` and the removal markers in
``marketplace_removed``. Both are created by
``storage.db._ensure_marketplace_tables()`` on engine startup.

Why a table and not a JSON file: the platform already stores the fact of
installation in six places (``skills.json``, ``removed_defaults.json``, the
RAG and connector manifests, the ``assistants.slug`` unique column and the
``DATA_DIR/*/<slug>`` folders). A seventh JSON registry declared as the only
source of truth would not survive manual edits (deleting a skill writes to
``removed_defaults.json``, not to the registry), would duplicate the DB
arbitration and is not atomic by nature: a corrupt file reads as an empty
registry. ``.marketplace/registry.json`` therefore stays as an exported
cache only.

Hashing area (D-04): ``entity_file_manifest()`` covers only the files a
package declares - never user data. For a skill that is ``SKILL.md`` and
the other catalog files minus ``scripts/*`` when code is not installed, for
a RAG base ``files/*`` but never ``index.db`` nor ``bm25_*`` (the first BM25
search rewrites the index, so hashing it would report a false modification).
"""
from __future__ import annotations

import json
import os
from typing import Dict, Iterable, List, Optional, Tuple

from core.marketplace import store


INSTALLED_TABLE = "marketplace_installed"
REMOVED_TABLE = "marketplace_removed"

ENTITY_TYPES = ("agent", "skill", "rag", "mcp")

# Paths that never participate in the installed-file manifest.
_VOLATILE_PREFIXES = ("__pycache__/", ".git/")
_VOLATILE_SUFFIXES = (".pyc", ".pyo")
# The index and the BM25 side tables are rewritten by the first search, and
# ``manifest.json`` is regenerated by every install: hashing any of them would
# report a modification of a base nobody touched.
_RAG_VOLATILE_NAMES = ("index.db", "index.db-wal", "index.db-shm", "manifest.json")
_RAG_VOLATILE_PREFIXES = ("bm25_",)
#: Per-run agent state that must never enter the file manifest.
_AGENT_VOLATILE_PREFIXES = ("memory/", "backups/", "sessions/", ".dev_agent/")


def _session():
    """Open a session on the main database (imported lazily to avoid cycles)."""
    from storage.db import get_session

    return get_session()


def _exec(session, sql: str, params: Optional[dict] = None):
    """Execute raw SQL on *session* and return the result proxy."""
    from sqlalchemy import text

    return session.execute(text(sql), params or {})


# ─── Runtime folder resolution ────────────────────────────────────────────

def skills_root() -> str:
    """Return the live skills library root (``DATA_DIR/skills``)."""
    from core.skills_library import get_skills_root

    return get_skills_root()


def rag_root() -> str:
    """Return the live RAG bases root (``DATA_DIR/rag_bases``)."""
    mod = __import__("sys").modules.get("core.paths")
    base = mod.DATA_DIR if mod is not None else store.data_dir()
    return os.path.join(base, "rag_bases")


def agents_root() -> str:
    """Return the live orchestrator folders root (``DATA_DIR/orchestrators``)."""
    from core.orchestrator_folders import get_orchestrators_root

    return get_orchestrators_root()


def assistants_root() -> str:
    """Return the live assistant folders root (``DATA_DIR/assistants``)."""
    from core.assistant_folders import get_assistants_root

    return get_assistants_root()


def installed_agent_kind(runtime_slug: str) -> str:
    """Return the recorded kind of an installed agent ('' when unknown).

    A row written before the column existed carries no kind; such an
    installation is an orchestrator, which is the only kind the platform
    had at the time. The lookup is deliberately a single query: every
    manifest helper resolves the folder first and must not open the
    registry twice.
    """
    if not runtime_slug:
        return ""
    from sqlalchemy import text

    session = _session()
    try:
        row = session.execute(
            text(
                f"SELECT agent_kind FROM {INSTALLED_TABLE} "
                "WHERE type = 'agent' AND runtime_slug = :slug LIMIT 1"
            ),
            {"slug": runtime_slug},
        ).first()
    except Exception:
        return ""
    finally:
        session.close()
    if row is None:
        return ""
    return str(row[0] or "")


def agent_folder(runtime_slug: str, agent_kind: str = "") -> Optional[str]:
    """Return the folder of an agent, existing or not.

    An agent is either an orchestrator (``DATA_DIR/orchestrators``) or an
    assistant (``DATA_DIR/assistants``). The recorded kind decides when it
    is known; otherwise the two roots are probed in the order the platform
    grew them, so a legacy row without a kind still resolves.
    """
    if not runtime_slug:
        return None
    kind = str(agent_kind or "").strip()
    if not kind:
        kind = installed_agent_kind(runtime_slug)
    if kind == "assistant":
        from core.assistant_folders import get_assistant_dir

        return get_assistant_dir(runtime_slug)
    if kind == "orchestrator":
        return os.path.join(agents_root(), runtime_slug)
    orchestrator = os.path.join(agents_root(), runtime_slug)
    if os.path.isdir(orchestrator):
        return orchestrator
    from core.assistant_folders import get_assistant_dir

    return get_assistant_dir(runtime_slug)


def runtime_folder(type_: str, runtime_slug: str) -> Optional[str]:
    """Return the absolute folder of an installed entity, or None.

    Skill folders live under ``DATA_DIR/skills``, RAG bases under
    ``DATA_DIR/rag_bases`` and agents under ``DATA_DIR/orchestrators``. An
    MCP entity is a connector record, not a folder, so it resolves to None.
    """
    if not runtime_slug:
        return None
    if type_ == "skill":
        path = os.path.join(skills_root(), runtime_slug)
    elif type_ == "rag":
        path = os.path.join(rag_root(), runtime_slug)
    elif type_ == "agent":
        # An agent lives either in the orchestrator root or in the assistant
        # root; ``agent_folder`` resolves which one without guessing.
        path = agent_folder(runtime_slug) or ""
    else:
        return None
    return path if os.path.isdir(path) else None


# ─── File manifest and hashes ─────────────────────────────────────────────

def _is_volatile(type_: str, rel_path: str) -> bool:
    """True when *rel_path* must stay out of the manifest."""
    normalized = rel_path.replace(os.sep, "/")
    if normalized.startswith(_VOLATILE_PREFIXES):
        return True
    if normalized.endswith(_VOLATILE_SUFFIXES):
        return True
    if type_ == "agent" and normalized.startswith(_AGENT_VOLATILE_PREFIXES):
        # Per-run state of an agent folder is not part of the installed
        # subset: hashing it would report a modification after every turn.
        return True
    if type_ == "rag":
        name = normalized.rsplit("/", 1)[-1]
        if name in _RAG_VOLATILE_NAMES:
            return True
        if name.startswith(_RAG_VOLATILE_PREFIXES):
            return True
    return False

def _sha256_file(path: str) -> str:
    """Return the hex sha256 of a file's content."""
    import hashlib

    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def entity_file_manifest(
    type_: str,
    runtime_slug: str,
    files: Optional[Dict[str, str]] = None,
) -> Dict[str, str]:
    """Return ``{relative path: sha256}`` for the hashing area of an entity.

    The hashing area (D-04) is the set of files a package declares, never
    the folder as a whole: a note the user dropped next to ``SKILL.md`` is
    theirs and must not look like a modification of the entity.

    Resolution order for the declared set:

      1. *files* - an explicit manifest from the installer or a caller;
      2. the installed registry row's ``files_json``;
      3. the folder walk, which is only correct for an entity that has no
         row yet - a legacy orphan being seeded.

    In cases 1 and 2 a declared path missing from disk is reported with an
    empty hash so the caller can tell "changed" from "deleted".
    """
    folder = runtime_folder(type_, runtime_slug)
    declared: Optional[Dict[str, str]] = files
    if declared is None:
        row = get_installed(type_, runtime_slug_id(type_, runtime_slug))
        if row is not None:
            declared = row.get("files_json") or None
    if folder is None:
        return {path: "" for path in declared} if declared else {}
    if declared:
        manifest: Dict[str, str] = {}
        for rel_path in declared:
            full = os.path.join(folder, rel_path)
            manifest[rel_path] = _sha256_file(full) if os.path.isfile(full) else ""
        return manifest
    manifest = {}
    for root, dirs, names in os.walk(folder):
        dirs[:] = [d for d in dirs if d != "__pycache__" and d != ".git"]
        for name in sorted(names):
            full = os.path.join(root, name)
            rel_path = os.path.relpath(full, folder).replace(os.sep, "/")
            if _is_volatile(type_, rel_path):
                continue
            try:
                manifest[rel_path] = _sha256_file(full)
            except OSError:
                manifest[rel_path] = ""
    return manifest


def runtime_slug_id(type_: str, runtime_slug: str) -> str:
    """Return the registry id whose ``runtime_slug`` is *runtime_slug*.

    The manifest helpers are keyed by the runtime folder name because that
    is what the caller has on hand (a package does not always know the
    catalog id). This lookup maps it back to the registry id, and returns
    the folder name unchanged when no row matches so a legacy orphan still
    resolves.
    """
    from sqlalchemy import text

    session = _session()
    try:
        row = session.execute(
            text(
                f"SELECT id FROM {INSTALLED_TABLE} "
                "WHERE type = :type AND runtime_slug = :slug LIMIT 1"
            ),
            {"type": type_, "slug": runtime_slug},
        ).first()
        return str(row[0]) if row is not None else runtime_slug
    except Exception:
        return runtime_slug
    finally:
        session.close()


def manifest_sha256(files: Dict[str, str]) -> str:
    """Return the stable hash of a ``{path: sha256}`` manifest.

    The hash covers sorted ``path\0sha256`` pairs, so it ignores walk order
    and mtime. Both the files of an installed entity and a not yet
    downloaded catalog manifest are hashed by the same function, which is
    what lets a version re-stamp be recognised without hashing anything on
    disk.
    """
    import hashlib

    digest = hashlib.sha256()
    for rel_path in sorted(files or {}):
        digest.update(rel_path.encode("utf-8"))
        digest.update(b"\0")
        digest.update(str(files[rel_path]).encode("utf-8"))
        digest.update(b"\n")
    return digest.hexdigest()


def tree_sha256(type_: str, runtime_slug: str, files: Optional[Dict[str, str]] = None) -> str:
    """Return a stable hash over the files of an installed entity.

    It is computed over the installed subset only, which keeps
    ``allow_code = false`` from producing a permanent ``user_modified``
    flag.
    """
    return manifest_sha256(entity_file_manifest(type_, runtime_slug, files))


# ─── Installed rows ───────────────────────────────────────────────────────

_INSTALLED_FIELDS = (
    "type", "id", "runtime_slug", "runtime_db_id", "runtime_skill_id",
    "fork_of", "version", "channel", "source_url", "package_sha256",
    "tree_sha256", "index_sha256", "files_json", "skipped_code_files_json",
    "installed_at", "updated_at", "installed_by", "user_modified",
    "user_modified_files_json", "install_id", "bundle_id", "pinned",
    "license_accepted_at", "agent_kind",
)

_JSON_FIELDS = ("files_json", "skipped_code_files_json", "user_modified_files_json")


def _row_to_dict(row) -> dict:
    """Convert a DB row to a dict with parsed JSON fields and bool flags."""
    data = dict(row._mapping) if hasattr(row, "_mapping") else dict(row)
    for field in _JSON_FIELDS:
        raw = data.get(field)
        if isinstance(raw, str):
            try:
                data[field] = json.loads(raw)
            except ValueError:
                data[field] = [] if field.endswith("_files_json") else {}
        elif raw is None:
            data[field] = [] if field.endswith("_files_json") else {}
    for flag in ("user_modified", "pinned"):
        data[flag] = bool(data.get(flag))
    return data


def get_installed(type_: str, id_: str) -> Optional[dict]:
    """Return the registry row of one entity, or None when not installed."""
    from sqlalchemy import text

    session = _session()
    try:
        row = session.execute(
            text(f"SELECT * FROM {INSTALLED_TABLE} WHERE type = :type AND id = :id"),
            {"type": type_, "id": id_},
        ).first()
        return _row_to_dict(row) if row is not None else None
    except Exception:
        return None
    finally:
        session.close()


def list_installed(type_: Optional[str] = None) -> List[dict]:
    """Return registry rows, optionally filtered by entity type."""
    session = _session()
    try:
        from sqlalchemy import text

        if type_:
            rows = session.execute(
                text(f"SELECT * FROM {INSTALLED_TABLE} WHERE type = :type ORDER BY id"),
                {"type": type_},
            ).all()
        else:
            rows = session.execute(
                text(f"SELECT * FROM {INSTALLED_TABLE} ORDER BY type, id")
            ).all()
        return [_row_to_dict(row) for row in rows]
    except Exception:
        return []
    finally:
        session.close()


def _coerce_record(record: dict) -> dict:
    """Normalise a record dict into DB column values."""
    values = {}
    for field in _INSTALLED_FIELDS:
        value = record.get(field)
        if field in _JSON_FIELDS:
            value = json.dumps(value if value is not None else (
                [] if field.endswith("_files_json") else {}), ensure_ascii=False)
        elif field in ("user_modified", "pinned"):
            value = 1 if value else 0
        values[field] = value
    return values


def upsert_installed(record: dict, session=None) -> None:
    """Insert or replace a registry row.

    When *session* is given the write joins the caller's transaction, which
    is what the installer needs: the registry row is written last, inside
    the same session that will be rolled back on failure.
    """
    from sqlalchemy import text

    values = _coerce_record(record)
    columns = ", ".join(values)
    placeholders = ", ".join(f":{name}" for name in values)
    own = session is None
    session = session or _session()
    try:
        session.execute(
            text(f"INSERT OR REPLACE INTO {INSTALLED_TABLE} ({columns}) VALUES ({placeholders})"),
            values,
        )
        if own:
            session.commit()
    finally:
        if own:
            session.close()


def update_installed(type_: str, id_: str, **fields) -> None:
    """Patch selected columns of an existing registry row."""
    if not fields:
        return
    from sqlalchemy import text

    assignments = []
    params = {"type": type_, "id": id_}
    for key, value in fields.items():
        if key in _JSON_FIELDS:
            value = json.dumps(value if value is not None else (
                [] if key.endswith("_files_json") else {}), ensure_ascii=False)
        elif key in ("user_modified", "pinned"):
            value = 1 if value else 0
        assignments.append(f"{key} = :{key}")
        params[key] = value
    session = _session()
    try:
        session.execute(
            text(f"UPDATE {INSTALLED_TABLE} SET {', '.join(assignments)} WHERE type = :type AND id = :id"),
            params,
        )
        session.commit()
    finally:
        session.close()
    export_registry_cache()


def remove_installed(type_: str, id_: str, session=None) -> None:
    """Delete a registry row (joining *session* when given)."""
    from sqlalchemy import text

    own = session is None
    session = session or _session()
    try:
        session.execute(
            text(f"DELETE FROM {INSTALLED_TABLE} WHERE type = :type AND id = :id"),
            {"type": type_, "id": id_},
        )
        if own:
            session.commit()
    finally:
        if own:
            session.close()


# ─── Removal markers ──────────────────────────────────────────────────────

def mark_removed(type_: str, id_: str, runtime_slug: str, via: str = "user") -> None:
    """Record that an entity was removed so nothing resurrects it.

    The row is what ``ensure_default_skills()`` consults as an additional
    source of removal markers, closing the gap where a deleted default skill
    came back on the next start.
    """
    from sqlalchemy import text

    session = _session()
    try:
        session.execute(
            text(
                f"INSERT OR REPLACE INTO {REMOVED_TABLE} "
                "(type, id, runtime_slug, removed_at, via) VALUES (:type, :id, :slug, :at, :via)"
            ),
            {"type": type_, "id": id_, "slug": runtime_slug,
             "at": store.isoformat_utc(), "via": via},
        )
        session.commit()
    finally:
        session.close()
    export_removed_cache()


def unmark_removed(type_: str, id_: str) -> None:
    """Drop a removal marker (used when the user reinstalls an entity)."""
    from sqlalchemy import text

    session = _session()
    try:
        session.execute(
            text(f"DELETE FROM {REMOVED_TABLE} WHERE type = :type AND id = :id"),
            {"type": type_, "id": id_},
        )
        session.commit()
    finally:
        session.close()
    export_removed_cache()


def is_removed(type_: str, id_: str) -> bool:
    """True when a removal marker exists for the entity."""
    from sqlalchemy import text

    session = _session()
    try:
        row = session.execute(
            text(f"SELECT 1 FROM {REMOVED_TABLE} WHERE type = :type AND id = :id"),
            {"type": type_, "id": id_},
        ).first()
        return row is not None
    except Exception:
        return False
    finally:
        session.close()


def list_removed(type_: Optional[str] = None) -> List[dict]:
    """Return removal markers, optionally filtered by entity type."""
    from sqlalchemy import text

    session = _session()
    try:
        if type_:
            rows = session.execute(
                text(f"SELECT * FROM {REMOVED_TABLE} WHERE type = :type ORDER BY id"),
                {"type": type_},
            ).all()
        else:
            rows = session.execute(text(f"SELECT * FROM {REMOVED_TABLE} ORDER BY type, id")).all()
        return [dict(row._mapping) for row in rows]
    except Exception:
        return []
    finally:
        session.close()


# ─── Legacy orphans ───────────────────────────────────────────────────────

def seed_local_orphans() -> List[dict]:
    """Register skills that exist on disk but have no marketplace row.

    Such skills were installed before the marketplace existed (or by hand).
    They get synthetic values - ``version`` ``0.0.0`` and channel ``legacy``
    - so their presence is visible in the UI without pretending to know a
    real version; the YaAgent migration replaces the version later from
    ``LEGACY_DEFAULTS``.

    A skill the user deleted (a removal marker exists for its derived id) is
    skipped, and skills already registered are left untouched.
    """
    from core.skills_library import list_skills

    installed = {(row["type"], row["id"]) for row in list_installed()}
    # A folder may already be owned by a catalog row whose id differs from
    # the derived ``local/<folder>`` one: the migration adopts bundled
    # entities under their catalog id, and seeding a second row for the same
    # folder would show one installation twice in the showcase.
    owned_folders = {
        (row["type"], str(row.get("runtime_slug") or ""))
        for row in list_installed()
    }
    seeded: List[dict] = []
    for skill in list_skills():
        folder = str(skill.get("folder") or "")
        if not folder:
            continue
        entity_id = f"local/{folder}"
        if ("skill", entity_id) in installed:
            continue
        if ("skill", folder) in owned_folders:
            continue
        if is_removed("skill", entity_id):
            continue
        manifest = entity_file_manifest("skill", folder)
        now = store.isoformat_utc()
        record = {
            "type": "skill",
            "id": entity_id,
            "runtime_slug": folder,
            "runtime_db_id": None,
            "runtime_skill_id": str(skill.get("id") or "") or None,
            "fork_of": None,
            "version": "0.0.0",
            "channel": "legacy",
            "source_url": "legacy",
            "package_sha256": None,
            "tree_sha256": tree_sha256("skill", folder, manifest),
            "index_sha256": None,
            "files_json": manifest,
            "skipped_code_files_json": [],
            "installed_at": now,
            "updated_at": now,
            "installed_by": "legacy_defaults",
            "user_modified": False,
            "user_modified_files_json": [],
            "install_id": None,
            "bundle_id": None,
            "pinned": False,
            "license_accepted_at": None,
        }
        try:
            upsert_installed(record)
        except Exception:
            continue
        seeded.append(record)
    if seeded:
        export_registry_cache()
    return seeded


# ─── Exported caches ──────────────────────────────────────────────────────

def _entity_key(row: dict) -> str:
    """Return the ``type:id`` key used in the exported registry cache."""
    return f"{row.get('type')}:{row.get('id')}"


def export_registry_cache() -> Optional[str]:
    """Write ``.marketplace/registry.json`` from the DB and return its path.

    The file is a cache for backup, migration and external tooling; nothing
    reads it back as a source of truth. A database that is not reachable
    (for example during an early test import) leaves the cache untouched.
    """
    rows = list_installed()
    if not rows:
        entities: Dict[str, dict] = {}
    else:
        entities = {_entity_key(row): row for row in rows}
    payload = {
        "schema": "sagaai.marketplace.registry/1",
        "updated_at": store.isoformat_utc(),
        "entities": entities,
    }
    try:
        store.atomic_write_json(store.registry_cache_path(), payload)
    except OSError:
        return None
    return store.registry_cache_path()


def export_removed_cache() -> Optional[str]:
    """Write ``.marketplace/removed.json`` from the DB and return its path."""
    markers = list_removed()
    payload = {
        "schema": "sagaai.marketplace.removed/1",
        "updated_at": store.isoformat_utc(),
        "markers": markers,
    }
    try:
        store.atomic_write_json(store.removed_cache_path(), payload)
    except OSError:
        return None
    return store.removed_cache_path()


def removed_source_markers() -> List[str]:
    """Return ``marketplace/<id>`` markers for skills removed via the catalog.

    ``ensure_default_skills()`` compares these against its own
    ``defaults/<folder>`` markers; a row whose ``runtime_slug`` matches a
    defaults folder under a ``marketplace/`` id is reported as
    ``defaults/<folder>`` so the default import skips it.
    """
    markers: List[str] = []
    for row in list_removed("skill"):
        entity_id = str(row.get("id") or "")
        slug = str(row.get("runtime_slug") or "")
        if not slug:
            continue
        if entity_id.startswith("defaults/"):
            markers.append(f"defaults/{slug}")
        elif entity_id == slug or entity_id.startswith("marketplace/"):
            markers.append(f"defaults/{slug}")
    return sorted(set(markers))


def ensure_tables() -> None:
    """Make sure the marketplace tables exist (idempotent).

    ``storage.db.get_engine()`` calls the same migration on startup; this
    wrapper lets the marketplace bootstrap run in contexts that only open a
    session and never touch the engine factory directly.
    """
    from storage.db import get_engine, _ensure_marketplace_tables

    _ensure_marketplace_tables(get_engine())
