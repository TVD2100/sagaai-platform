# -*- coding: utf-8 -*-
"""core.orchestration.runs - the durable run store of the orchestration runtime.

Why this exists: the in-memory run registry disappears with the process, and
``release_tree`` drops it on purpose when a dialog finishes a step. A
background child keeps working after that, so its status has to survive on
disk - otherwise the parent can never learn how it ended and
``resume_subagent`` has nothing to resume from.

Storage contract:

- one JSON file per run, at ``<store_root>/<root_run_id>/<ts>_<run_id>.json``.
  The directory name IS the tree id, so listing a tree never opens a foreign
  file and pruning is a sort over file names instead of parsing every record.
- ``store_root`` is an EXPLICIT argument of every function. It must not be
  read from the process-wide config here: that config belongs to whichever
  dialog is running right now, and a background worker re-reading it would
  write its record into another project's folder.
- writes are atomic (temporary file in the same directory + ``os.replace``),
  so a reader never sees half a record and a crash never leaves a truncated
  file behind.
- a broken file is renamed to ``*.corrupt`` and skipped: one bad record must
  not blind the whole list.
- :func:`heal` runs inside the read path and turns a record that still claims
  ``running`` but whose process is gone into ``failed``/``stale_run``.
  Without it a crashed run would look alive forever and keep its tree from
  being released.

Exactly-once notices are guarded here too: :func:`claim_notice` creates a lock
file with ``O_CREAT | O_EXCL``, which is atomic across threads AND across
processes. A marker inside the message text cannot do that - two writers would
both see no marker and both write.
"""

from __future__ import annotations

import json
import logging
import os
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from core.orchestration.contracts import (
    DEFAULT_SUBAGENT_TIMEOUT_SECONDS,
    ERR_STALE_RUN,
    STATUS_FAILED,
    STATUS_RUNNING,
    STOP_ERROR,
)

log = logging.getLogger("core.orchestration.runs")

#: Sub-directory of the store root that holds notice claim keys.
NOTICES_DIR = "notices"

#: How many records one root may keep before the oldest are pruned.
MAX_RECORDS_PER_ROOT = 200

#: Lower bound of the staleness window: a heartbeat older than this is always
#: considered dead, whatever the run timeout says.
STALE_MIN_SECONDS = 60.0

#: Identity of THIS process instance. A record carrying another value was
#: written by a previous process, whose daemon threads no longer exist.
_BOOT_ID = uuid.uuid4().hex


def current_boot_id() -> str:
    """Return the identity of this process instance."""
    return _BOOT_ID


def default_store_root() -> str:
    """Return the store root of the current installation.

    Orchestration state belongs to the PLATFORM, not to the package tree and
    not to the user's project: writing records next to the source modules
    pollutes the repository (and the published file set), while
    ``PROJECT_ROOT`` points at whatever folder the dialog works on - a
    different and mutable thing. The platform runtime folder is therefore the
    single anchor: ``<install>/.dev_agent/orchestration``.
    """
    try:
        from dev_agent import config as _config
        install_root = Path(getattr(_config, "INSTALL_ROOT", "") or ".")
        runtime = Path(getattr(_config, "_RUNTIME_DIR", "") or ".")
        # ``_RUNTIME_DIR`` lives INSIDE the package when the agent works on its
        # own install; state must never be mixed with source files there.
        package_dir = Path(getattr(_config, "DEV_AGENT_DIR", "") or ".").resolve()
        if runtime.resolve() == package_dir:
            base = install_root / ".dev_agent"
        else:
            base = runtime
    except Exception:  # pragma: no cover - config is best effort
        base = Path(".dev_agent")
    return str(base / "orchestration")


def _now_iso() -> str:
    """Return the current UTC time as an ISO-8601 string."""
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _safe_name(value: Any) -> str:
    """Return *value* as a filesystem-safe name component.

    Run and root ids are generated by the platform, but a hand-edited config or
    an imported tree may carry slashes or dots; a traversal here would let a
    record escape the store.
    """
    raw = str(value or "").strip()
    if not raw:
        return "unknown"
    out = []
    for ch in raw:
        out.append(ch if (ch.isalnum() or ch in "-_.") else "_")
    name = "".join(out).strip(".")
    return name[:120] or "unknown"


def _tree_dir(store_root: str, root_run_id: Any) -> Path:
    """Return the directory that holds the records of one root tree."""
    return Path(store_root or default_store_root()) / _safe_name(root_run_id)


def _iter_record_files(store_root: str,
                       root_run_id: Optional[str] = None) -> List[Path]:
    """Return record files of one tree, or of every tree when root is None."""
    base = Path(store_root or default_store_root())
    if not base.is_dir():
        return []
    if root_run_id:
        target = _tree_dir(str(base), root_run_id)
        dirs = [target] if target.is_dir() else []
    else:
        try:
            dirs = [d for d in base.iterdir()
                    if d.is_dir() and d.name != NOTICES_DIR]
        except OSError:  # pragma: no cover - unreadable store
            return []
    files: List[Path] = []
    for directory in dirs:
        try:
            files.extend(p for p in directory.iterdir()
                         if p.is_file() and p.suffix == ".json")
        except OSError:  # pragma: no cover - unreadable tree
            continue
    return files


def _find_record_file(run_id: str, store_root: str) -> Optional[Path]:
    """Return the newest record file of *run_id*, or None.

    The file name carries a timestamp prefix so several records of one run
    sort chronologically by name; the newest wins.
    """
    rid = _safe_name(run_id)
    if not rid:
        return None
    candidates = [p for p in _iter_record_files(store_root)
                  if p.stem.endswith("_" + rid)]
    if not candidates:
        return None
    return max(candidates, key=lambda p: (p.stat().st_mtime, p.name))


def _read_file(path: Path) -> Optional[Dict[str, Any]]:
    """Read one record; a broken file is set aside instead of raising."""
    try:
        with open(path, "r", encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, ValueError):
        try:
            path.replace(path.with_suffix(path.suffix + ".corrupt"))
        except OSError:  # pragma: no cover - rename is best effort
            pass
        return None
    return data if isinstance(data, dict) else None


def _pid_alive(pid: int) -> bool:
    """Return True when *pid* exists (POSIX signal 0 probe)."""
    try:
        os.kill(int(pid), 0)
    except (OSError, ValueError, OverflowError):
        return False
    return True


def heal(record: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    """Return ``(record, changed)`` with a dead ``running`` claim repaired.

    Three independent signals mark a claim as dead: a heartbeat older than
    ``max(STALE_MIN_SECONDS, 2 x run timeout)``, a ``boot_id`` of another
    process instance, or a ``pid`` that no longer exists. Any of them turns the
    record into ``failed``/``stale_run``; the reason is recorded so an
    operator can tell a crash from a hang.
    """
    if not isinstance(record, dict):
        return record, False
    if str(record.get("status") or "") != STATUS_RUNNING:
        return record, False

    try:
        heartbeat = float(record.get("heartbeat_at") or 0.0)
    except (TypeError, ValueError):
        heartbeat = 0.0
    try:
        timeout = float(record.get("timeout_seconds")
                        or DEFAULT_SUBAGENT_TIMEOUT_SECONDS)
    except (TypeError, ValueError):
        timeout = float(DEFAULT_SUBAGENT_TIMEOUT_SECONDS)
    threshold = max(STALE_MIN_SECONDS, 2.0 * timeout)

    reasons: List[str] = []
    if heartbeat <= 0 or (time.time() - heartbeat) > threshold:
        reasons.append("heartbeat")
    writer_boot = str(record.get("boot_id") or "")
    if writer_boot and writer_boot != current_boot_id():
        reasons.append("boot")
    pid = record.get("pid")
    if (reasons == [] and isinstance(pid, int) and pid > 0
            and writer_boot == current_boot_id() and not _pid_alive(pid)):
        reasons.append("pid")
    if not reasons:
        return record, False

    healed = dict(record)
    healed["status"] = STATUS_FAILED
    healed["stop_reason"] = STOP_ERROR
    healed["error_code"] = ERR_STALE_RUN
    healed["stale_reason"] = ",".join(reasons)
    healed["updated_at"] = _now_iso()
    return healed, True


def save(record: Dict[str, Any], store_root: str = "") -> bool:
    """Write one run record atomically; return True on success.

    A record already on disk for the same ``run_id`` is rewritten in place, so
    repeated saves (start, heartbeat, finish) never accumulate duplicates.
    A failure is logged and reported, never raised: losing observability must
    not break the run itself.
    """
    if not isinstance(record, dict):
        return False
    run_id = _safe_name(record.get("run_id"))
    if not run_id:
        return False
    data = dict(record)
    data.setdefault("updated_at", _now_iso())

    existing = _find_record_file(run_id, store_root)
    if existing is not None:
        target = existing
        directory = existing.parent
    else:
        directory = _tree_dir(store_root, data.get("root_run_id") or run_id)
        stamp = "%013d" % int(time.time() * 1000)
        target = directory / (stamp + "_" + run_id + ".json")

    tmp = target.with_name(target.name + ".tmp." + uuid.uuid4().hex[:8])
    try:
        directory.mkdir(parents=True, exist_ok=True)
        with open(tmp, "w", encoding="utf-8") as handle:
            json.dump(data, handle, ensure_ascii=False, indent=1)
        os.replace(str(tmp), str(target))
    except OSError as exc:
        log.warning("run record save failed for %s: %s", run_id, exc)
        try:
            if tmp.exists():
                tmp.unlink()
        except OSError:  # pragma: no cover - cleanup is best effort
            pass
        return False

    try:
        _dedupe_run_records(run_id, store_root,
                            root_run_id=data.get("root_run_id") or run_id)
    except Exception as exc:  # pragma: no cover - dedupe must not break a save
        log.debug("run record dedupe skipped: %s", exc)

    try:
        prune_root(data.get("root_run_id") or run_id, store_root)
    except Exception as exc:  # pragma: no cover - pruning must not break saves
        log.debug("run record prune skipped: %s", exc)
    return True


def _dedupe_run_records(run_id: str, store_root: str = "",
                        root_run_id: Optional[str] = None) -> int:
    """Delete older duplicate files of one run, keeping the newest.

    Two writers that both miss the existing file each create their own
    timestamped name: the record stays readable (``_find_record_file`` picks
    the newest), but the tree collects copies of one run and ``prune_root``
    can drop a live one while a duplicate survives. Every save therefore ends
    with this sweep, so the LAST writer leaves exactly one file behind.
    """
    rid = _safe_name(run_id)
    if not rid:
        return 0
    tree = _safe_name(root_run_id) if root_run_id else None
    try:
        candidates = [p for p in _iter_record_files(store_root, tree)
                      if p.stem.endswith("_" + rid)]
    except Exception:  # pragma: no cover - a listing failure must not break a save
        return 0
    if len(candidates) <= 1:
        return 0

    def _key(path: Path):
        try:
            return (path.stat().st_mtime, path.name)
        except OSError:  # pragma: no cover - racing delete
            return (0.0, path.name)

    keeper = max(candidates, key=_key)
    removed = 0
    for path in candidates:
        if path == keeper:
            continue
        try:
            path.unlink()
            removed += 1
        except OSError:  # pragma: no cover - racing delete
            continue
    return removed


def load(run_id: str, store_root: str = "") -> Optional[Dict[str, Any]]:
    """Return one record with :func:`heal` applied, or None."""
    path = _find_record_file(run_id, store_root)
    if path is None:
        return None
    record = _read_file(path)
    if record is None:
        return None
    healed, changed = heal(record)
    if changed:
        save(healed, store_root)
    return healed


def list_runs(root_run_id: Optional[str] = None, store_root: str = "",
              limit: int = 50) -> List[Dict[str, Any]]:
    """Return recent records of one tree (newest first), or of all trees."""
    files = _iter_record_files(store_root, root_run_id)
    if not files:
        return []
    def _stamp(path: Path) -> float:
        try:
            return path.stat().st_mtime
        except OSError:  # pragma: no cover - racing delete
            return 0.0
    files.sort(key=_stamp, reverse=True)
    out: List[Dict[str, Any]] = []
    seen: set = set()
    for path in files:
        record = _read_file(path)
        if record is None:
            continue
        healed, changed = heal(record)
        if changed:
            save(healed, store_root)
        rid = str(healed.get("run_id") or "")
        if rid and rid in seen:
            continue
        seen.add(rid)
        out.append(healed)
        if limit and len(out) >= int(limit):
            break
    return out


def prune_root(root_run_id: str, store_root: str = "",
               keep: int = MAX_RECORDS_PER_ROOT) -> int:
    """Delete the oldest records of one tree beyond *keep*; return the count.

    Ordering is by file NAME, which starts with a millisecond timestamp: no
    record has to be opened to know which are the oldest.
    """
    if keep < 1:
        keep = 1
    directory = _tree_dir(store_root, root_run_id)
    if not directory.is_dir():
        return 0
    try:
        names = sorted(p for p in directory.iterdir()
                       if p.is_file() and p.suffix == ".json")
    except OSError:  # pragma: no cover - unreadable tree
        return 0
    excess = len(names) - int(keep)
    removed = 0
    for path in names[:max(0, excess)]:
        try:
            path.unlink()
            removed += 1
        except OSError:  # pragma: no cover - racing delete
            continue
    return removed


def remove_older_than(days: float, store_root: str = "") -> int:
    """Delete records older than *days* across every tree; return the count.

    Called lazily when a service starts, never on the finish path of a worker:
    housekeeping must not extend the critical path of a completion.
    """
    try:
        horizon = time.time() - float(days) * 86400.0
    except (TypeError, ValueError):
        return 0
    removed = 0
    for path in _iter_record_files(store_root):
        try:
            if path.stat().st_mtime < horizon:
                path.unlink()
                removed += 1
        except OSError:  # pragma: no cover - racing delete
            continue
    return removed


def claim_notice(run_id: str, status: str, store_root: str = "") -> bool:
    """Claim the right to publish one notice; True for the first caller only.

    ``O_CREAT | O_EXCL`` is the atomic primitive here: it succeeds for exactly
    one caller across threads and processes, which is what a notice needs to
    appear once even when both the loop and the UI try to publish it.
    """
    rid = _safe_name(run_id)
    if not rid:
        return False
    directory = Path(store_root or default_store_root()) / NOTICES_DIR
    target = directory / (rid + "." + _safe_name(status) + ".lck")
    try:
        directory.mkdir(parents=True, exist_ok=True)
        handle = os.open(str(target), os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
    except FileExistsError:
        return False
    except OSError as exc:
        log.warning("notice claim failed for %s: %s", rid, exc)
        return False
    try:
        os.write(handle, _now_iso().encode("utf-8"))
    finally:
        os.close(handle)
    return True


def notice_claimed(run_id: str, status: str, store_root: str = "") -> bool:
    """Return True when a notice for this run and status was already claimed."""
    rid = _safe_name(run_id)
    if not rid:
        return False
    target = (Path(store_root or default_store_root()) / NOTICES_DIR
              / (rid + "." + _safe_name(status) + ".lck"))
    return target.exists()
