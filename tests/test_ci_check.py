"""
test_ci_check.py - the repository's local/CI gate runner.

The runner is the single place the checks live: the workflow only calls it.
These tests pin the parts a broken edit would silently weaken - parsing the
declared requirements and the lock, comparing them, and the exit code the
caller (a shell, a CI job) acts on.
"""
import json
import sys
from pathlib import Path

import pytest

PKG_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PKG_ROOT))
sys.path.insert(0, str(PKG_ROOT / "scripts"))

import ci_check  # noqa: E402 - after sys.path preparation


# ── parsing ──────────────────────────────────────────────────────────────────

def test_parse_requirements_reads_names_and_specifiers(tmp_path):
    """A normal file becomes {name: specifier}; comments and options vanish."""
    path = tmp_path / "requirements.txt"
    path.write_text(
        "# a comment\n"
        "streamlit>=1.66.0\n"
        "sqlalchemy>=2.0,<3.0\n"
        "httpx[http2]==0.28.1  # inline note\n"
        "--find-links ./wheels\n"
        "-r other.txt\n"
        "\n"
        "plainpkg\n",
        encoding="utf-8",
    )
    entries = ci_check.parse_requirements(str(path))
    assert entries == {
        "streamlit": ">=1.66.0",
        "sqlalchemy": ">=2.0,<3.0",
        "httpx": "==0.28.1",
        "plainpkg": "",
    }


def test_parse_requirements_keeps_a_full_range_specifier(tmp_path):
    """An upper bound is part of the specifier, not a comment to be dropped."""
    path = tmp_path / "requirements.txt"
    path.write_text("streamlit>=1.66.0,<2.0\nrequests>=2.28,<3.0\n", encoding="utf-8")
    entries = ci_check.parse_requirements(str(path))
    assert entries == {"streamlit": ">=1.66.0,<2.0", "requests": ">=2.28,<3.0"}
    assert ci_check.satisfies("1.99.0", entries["streamlit"]) is True
    assert ci_check.satisfies("2.0.0", entries["streamlit"]) is False


def test_parse_lock_collects_pins_and_hash_counts(tmp_path):
    """Each ``name==version`` line and its following --hash lines are recorded."""
    path = tmp_path / "requirements.lock"
    path.write_text(
        "# generated by pip-compile\n"
        "streamlit==1.66.0 \\\n"
        "    --hash=sha256:aaa \\\n"
        "    --hash=sha256:bbb\n"
        "sqlalchemy==2.0.50 \\\n"
        "    --hash=sha256:ccc\n"
        "packaging==25.0\n",
        encoding="utf-8",
    )
    versions, hashes = ci_check.parse_lock(str(path))
    assert versions == {"streamlit": "1.66.0", "sqlalchemy": "2.0.50", "packaging": "25.0"}
    assert hashes["streamlit"] == 2
    assert hashes["sqlalchemy"] == 1
    assert hashes["packaging"] == 0


@pytest.mark.parametrize("pinned,specifier,expected", [
    ("1.66.0", ">=1.66.0", True),
    ("1.67.2", ">=1.66.0", True),
    ("1.65.9", ">=1.66.0", False),
    ("2.0.50", ">=2.0,<3.0", True),
    ("3.0.1", ">=2.0,<3.0", False),
    ("1.66", ">=1.66.0", True),
    ("0.28.1", "==0.28.1", True),
    ("0.28.2", "==0.28.1", False),
    ("1.66.0", "", True),
    ("somename", ">=1.0", False),
    ("5.9.0", "~=5.9", True),
    ("6.0.0", "~=5.9", False),
])
def test_satisfies_compares_numeric_components(pinned, specifier, expected):
    assert ci_check.satisfies(pinned, specifier) is expected


# ── lock comparison ──────────────────────────────────────────────────────────

def test_compare_lock_is_empty_when_every_declared_package_agrees():
    requirements = {"streamlit": ">=1.66.0", "sqlalchemy": ">=2.0"}
    versions = {"streamlit": "1.66.0", "sqlalchemy": "2.0.50", "packaging": "25.0"}
    hashes = {"streamlit": 3, "sqlalchemy": 2, "packaging": 1}
    assert ci_check.compare_lock(requirements, versions, hashes) == []


def test_compare_lock_reports_a_missing_package():
    problems = ci_check.compare_lock({"streamlit": ">=1.66.0"}, {"sqlalchemy": "2.0"}, {"sqlalchemy": 1})
    assert any("streamlit" in item and "missing" in item for item in problems)


def test_compare_lock_reports_a_version_outside_the_declared_range():
    problems = ci_check.compare_lock({"streamlit": ">=1.66.0"}, {"streamlit": "1.10.0"}, {"streamlit": 2})
    assert any("streamlit" in item and "does not satisfy" in item for item in problems)


def test_compare_lock_reports_a_package_without_hashes():
    problems = ci_check.compare_lock({"streamlit": ">=1.66.0"}, {"streamlit": "1.66.0"}, {})
    assert any("no --hash" in item for item in problems)


# ── the lock check itself ────────────────────────────────────────────────────

def _redirect(monkeypatch, tmp_path, requirements, lock, api_requirements=""):
    """Point the lock check at temporary files instead of the repository ones."""
    requirements_path = tmp_path / "requirements.txt"
    requirements_path.write_text(requirements, encoding="utf-8")
    monkeypatch.setattr(ci_check, "REQUIREMENTS_PATH", str(requirements_path))
    api_path = tmp_path / "requirements-api.txt"
    api_path.write_text(api_requirements, encoding="utf-8")
    monkeypatch.setattr(ci_check, "REQUIREMENTS_API_PATH", str(api_path))
    if lock is None:
        monkeypatch.setattr(ci_check, "LOCK_PATH", str(tmp_path / "requirements.lock"))
    else:
        lock_path = tmp_path / "requirements.lock"
        lock_path.write_text(lock, encoding="utf-8")
        monkeypatch.setattr(ci_check, "LOCK_PATH", str(lock_path))


def test_check_lock_passes_when_the_lock_does_not_exist_yet(monkeypatch, tmp_path):
    """Before the lock is introduced the cross-check is reported, not failed."""
    _redirect(monkeypatch, tmp_path, "streamlit>=1.66.0\n", None)
    status, detail = ci_check.check_lock()
    assert status == "ok"
    assert "not in force" in detail


def test_check_lock_fails_when_the_lock_disagrees(monkeypatch, tmp_path):
    _redirect(monkeypatch, tmp_path, "streamlit>=1.66.0\n",
              "streamlit==1.10.0 \\\n    --hash=sha256:aaa\n")
    status, detail = ci_check.check_lock()
    assert status == "fail"
    assert "streamlit" in detail


def test_check_lock_passes_when_the_lock_agrees(monkeypatch, tmp_path):
    _redirect(monkeypatch, tmp_path, "streamlit>=1.66.0\n",
              "streamlit==1.66.0 \\\n    --hash=sha256:aaa\n")
    status, detail = ci_check.check_lock()
    assert status == "ok"
    assert "agrees" in detail


def test_check_lock_fails_when_the_lock_lists_nothing(monkeypatch, tmp_path):
    _redirect(monkeypatch, tmp_path, "streamlit>=1.66.0\n", "# empty lock\n")
    status, _ = ci_check.check_lock()
    assert status == "fail"


def test_check_lock_covers_the_api_constraints(monkeypatch, tmp_path):
    """A distribution declared only in requirements-api.txt is checked too.

    The API tests run whenever fastapi is installed, so a lock that omits it
    would quietly turn them into skips instead of failing the pipeline.
    """
    _redirect(monkeypatch, tmp_path, "streamlit>=1.66.0\n",
              "streamlit==1.66.0 \\\n    --hash=sha256:aaa\n",
              api_requirements="fastapi>=0.115,<1.0\n")
    status, detail = ci_check.check_lock()
    assert status == "fail"
    assert "fastapi" in detail


def test_check_lock_passes_when_both_constraint_files_agree(monkeypatch, tmp_path):
    _redirect(monkeypatch, tmp_path, "streamlit>=1.66.0\n",
              "streamlit==1.66.0 \\\n    --hash=sha256:aaa\n"
              "fastapi==0.141.1 \\\n    --hash=sha256:bbb\n",
              api_requirements="fastapi>=0.115,<1.0\n")
    status, detail = ci_check.check_lock()
    assert status == "ok"
    assert "2 declared" in detail


# ── the runner contract ──────────────────────────────────────────────────────

def test_list_prints_every_check_name_in_order(capsys):
    assert ci_check.main(["--list"]) == 0
    printed = capsys.readouterr().out.split()
    assert printed == [name for name, _ in ci_check.CHECKS]


def test_unknown_check_name_is_a_usage_error(capsys):
    assert ci_check.main(["--only", "nosuchcheck"]) == 2
    assert "unknown check" in capsys.readouterr().err


def test_run_reports_success_only_when_every_selected_check_passes(monkeypatch, capsys):
    """One failing check must make the whole run fail, not be swallowed."""
    calls = []

    def passing():
        calls.append("ok")
        return "ok", "fine"

    def failing():
        calls.append("fail")
        return "fail", "broken"

    monkeypatch.setattr(ci_check, "CHECKS", [("good", passing), ("bad", failing)])
    assert ci_check.main([]) == 1
    assert calls == ["ok", "fail"]
    output = capsys.readouterr().out
    assert "[PASS] good" in output and "[FAIL] bad" in output


def test_environment_error_outranks_a_plain_failure(monkeypatch):
    monkeypatch.setattr(ci_check, "CHECKS", [("broken", lambda: ("fail", "x")),
                                             ("missing", lambda: ("env", "y"))])
    assert ci_check.main([]) == 2


def test_only_runs_the_requested_subset(monkeypatch):
    calls = []
    monkeypatch.setattr(ci_check, "CHECKS", [
        ("first", lambda: (calls.append("first"), ("ok", ""))[1]),
        ("second", lambda: (calls.append("second"), ("ok", ""))[1]),
    ])
    assert ci_check.main(["--only", "second"]) == 0
    assert calls == ["second"]


# ── exit-code mapping of the real checks ────────────────────────────────────
#
# These tests deliberately do NOT assert that the current tree is clean. The
# manifest legitimately disagrees with the tree while a change is being made,
# and a suite that fails for that reason would be red for most of a working
# day. What must be pinned is the mapping: a tool's exit code decides whether
# the gate passed, failed or could not run.

def test_ruff_findings_fail_the_check(monkeypatch):
    monkeypatch.setattr(ci_check, "run_process", lambda command, timeout=0: (1, "F401 unused import"))
    status, detail = ci_check.check_ruff()
    assert status == "fail"
    assert "F401" in detail


def test_missing_ruff_is_an_environment_error(monkeypatch):
    monkeypatch.setattr(ci_check, "run_process",
                        lambda command, timeout=0: (127, "ruff: command not found"))
    assert ci_check.check_ruff()[0] == "env"


def test_manifest_violations_fail_the_check(monkeypatch):
    monkeypatch.setattr(ci_check, "run_process",
                        lambda command, timeout=0: (1, "ERROR: sha256 mismatch: ruff.toml"))
    status, detail = ci_check.check_manifest()
    assert status == "fail"
    assert "sha256 mismatch" in detail


def test_unrunnable_manifest_check_is_an_environment_error(monkeypatch):
    monkeypatch.setattr(ci_check, "run_process", lambda command, timeout=0: (2, "fatal"))
    assert ci_check.check_manifest()[0] == "env"


def test_failing_tests_fail_the_check(monkeypatch):
    monkeypatch.setattr(ci_check, "run_process",
                        lambda command, timeout=0: (1, "1 failed, 4437 passed"))
    status, detail = ci_check.check_tests()
    assert status == "fail"
    assert "1 failed" in detail


def test_empty_test_run_is_a_failure_not_a_pass(monkeypatch):
    """Exit code 5 means pytest collected nothing - a green gate would lie."""
    monkeypatch.setattr(ci_check, "run_process", lambda command, timeout=0: (5, "no tests ran"))
    assert ci_check.check_tests()[0] == "fail"


def test_passing_tests_report_the_summary_line(monkeypatch):
    monkeypatch.setattr(ci_check, "run_process",
                        lambda command, timeout=0: (0, "....\n4438 passed in 166.70s"))
    status, detail = ci_check.check_tests()
    assert status == "ok"
    assert "4438 passed" in detail


# ── the type budget ─────────────────────────────────────────────────────────
#
# The check reads a small JSON budget and one pyright report. Both are cheap
# to fake, so the contract is pinned without running pyright at all: a
# missing budget passes (the check is not in force yet), a broken one is an
# environment error, and a count above the budget fails.


def _report(errors: int) -> str:
    return json.dumps({"summary": {"errorCount": errors, "warningCount": 3,
                                   "filesAnalyzed": 159},
                       "generalDiagnostics": []})


def _budget(tmp_path, monkeypatch, payload) -> str:
    """Write a budget file and point the check at it; return its path."""
    path = tmp_path / "pyright_budget.json"
    if payload is not None:
        path.write_text(payload if isinstance(payload, str)
                        else json.dumps(payload), encoding="utf-8")
    monkeypatch.setattr(ci_check, "PYRIGHT_BUDGET_PATH", str(path))
    return str(path)


def test_a_missing_budget_passes_with_an_explanation(tmp_path, monkeypatch):
    """The check is not in force until the file is committed - not a failure."""
    _budget(tmp_path, monkeypatch, None)
    status, detail = ci_check.check_types()
    assert status == "ok"
    assert "not in force" in detail


def test_an_unreadable_budget_is_an_environment_error(tmp_path, monkeypatch):
    """A budget the check cannot parse is a broken environment, not a finding."""
    _budget(tmp_path, monkeypatch, "{not json")
    assert ci_check.check_types()[0] == "env"


def test_a_budget_without_a_number_is_an_environment_error(tmp_path, monkeypatch):
    _budget(tmp_path, monkeypatch, {"packages": ["core"]})
    assert ci_check.check_types()[0] == "env"


def test_a_budget_without_packages_is_an_environment_error(tmp_path, monkeypatch):
    """Analysing nothing would compare 0 against the budget and always pass."""
    _budget(tmp_path, monkeypatch, {"max_errors": 1, "packages": []})
    assert ci_check.check_types()[0] == "env"


def test_a_count_above_the_budget_fails(tmp_path, monkeypatch):
    _budget(tmp_path, monkeypatch, {"max_errors": 10, "packages": ["core"]})
    monkeypatch.setattr(ci_check, "run_process",
                        lambda command, timeout=0: (1, _report(11)))
    status, detail = ci_check.check_types()
    assert status == "fail"
    assert "11" in detail and "10" in detail


def test_a_count_equal_to_the_budget_passes(tmp_path, monkeypatch):
    """Equal is inside the budget: the budget is the permitted maximum."""
    _budget(tmp_path, monkeypatch, {"max_errors": 10, "packages": ["core"]})
    monkeypatch.setattr(ci_check, "run_process",
                        lambda command, timeout=0: (1, _report(10)))
    assert ci_check.check_types()[0] == "ok"


def test_a_count_below_the_budget_passes(tmp_path, monkeypatch):
    """A fix must never be punished for not editing the budget file first."""
    _budget(tmp_path, monkeypatch, {"max_errors": 10, "packages": ["core"]})
    monkeypatch.setattr(ci_check, "run_process",
                        lambda command, timeout=0: (1, _report(4)))
    status, detail = ci_check.check_types()
    assert status == "ok"
    assert "4" in detail


def test_the_command_analyses_the_packages_of_the_budget(tmp_path, monkeypatch):
    """The package list comes from the budget, not from the caller."""
    _budget(tmp_path, monkeypatch,
            {"max_errors": 10, "packages": ["core", "server"]})
    seen = []
    monkeypatch.setattr(ci_check, "run_process",
                        lambda command, timeout=0: (seen.append(command),
                                                    (1, _report(0)))[1])
    ci_check.check_types()
    assert seen, "pyright was never invoked"
    # The packages are the TAIL of the command, whichever way pyright is
    # launched (a console script, or ``python -m pyright``).
    assert seen[0][-2:] == ["core", "server"]


def test_missing_pyright_is_an_environment_error(tmp_path, monkeypatch):
    _budget(tmp_path, monkeypatch, {"max_errors": 10, "packages": ["core"]})
    monkeypatch.setattr(ci_check, "run_process",
                        lambda command, timeout=0: (127, "pyright: command not found"))
    assert ci_check.check_types()[0] == "env"


def test_an_unparsable_report_fails_the_check(tmp_path, monkeypatch):
    """A syntax error in the source makes pyright print no report."""
    _budget(tmp_path, monkeypatch, {"max_errors": 10, "packages": ["core"]})
    monkeypatch.setattr(ci_check, "run_process",
                        lambda command, timeout=0: (1, "core/x.py:1:1 syntax error"))
    assert ci_check.check_types()[0] == "fail"


def test_the_type_check_runs_before_the_manifest(monkeypatch):
    """Order matters for the reader: cheap syntax-level gates go first."""
    names = [name for name, _ in ci_check.CHECKS]
    assert names.index("types") < names.index("manifest")
